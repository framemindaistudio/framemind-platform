export function rules({ project }: DocInput) {
  return `# Rules — ${s(project.title)}

> Owner: Tech Lead · FrameMind's standard rules. Add project-specific ones below — HQ won't overwrite this file.

## Branches
- \`main\` is production. Nobody pushes to it directly; changes reach it only through a pull request merged from FrameMind HQ.
- One branch per task, created by HQ: \`feature/<ID>-<short-description>\`, \`fix/<ID>-…\`, \`hotfix/<ID>-…\`.

## Commits
- Start every commit message with the task ID: \`FM-104: Build client login form\`.
- Small, focused commits. No generated files, secrets or \`.env\` files.

## Pull requests
- Open the PR from HQ (or GitHub) when the task's acceptance criteria are met.
- CI must pass, and someone other than the author must approve the latest commit. New commits need a fresh review.

## Code
- Follow the existing structure and naming; no new dependencies without the Tech Lead's OK.
- Handle errors and empty states; no console noise left behind.

## Definition of done
- Acceptance criteria met, CI green, reviewed and approved, merged from HQ, preview checked.

## Project-specific rules
${TODO("Tech Lead")}
`;
}

