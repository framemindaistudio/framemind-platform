/** Every file HQ writes, with whether HQ owns it (rewritten) or only seeds it (written once). */
export function founderSummary({ project }: DocInput) {
  return `# Founder summary — ${s(project.title)}

> The founder's decision on what we are building. It overrides the client's submission wherever they differ.
> Edited in FrameMind HQ (project → Development) — HQ rewrites this file; don't edit it here.

${s(project.founderBrief) || "_Not written yet._"}
`;
}

export function clientRequirements({ project, client, submission }: DocInput) {
  const sub = submission ?? {};
  const field = (label: string, v: unknown) => (s(v) ? `## ${label}\n${s(v)}\n` : "");
  const colors = Array.isArray(sub.colors) ? (sub.colors as string[]) : [];
  return `# Client requirements — ${s(project.title)}

> What the client submitted in the FrameMind client portal${s(sub.status) === "approved" ? " (approved by the founder)" : ""}. Written by FrameMind HQ.

${field("Organisation", s(sub.company) || s(client?.name))}${field("About", sub.about)}${field("Audience", sub.audience)}${field("Requirements", s(sub.requirements) || s(project.brief))}${field("Pages / sections", sub.pages)}${colors.length ? `## Brand colours\n${colors.join(", ")}\n` : ""}${field("Fonts", sub.fonts)}${field("Current website", sub.website)}${field("Reference links", sub.referenceLinks)}${s(sub.logo) ? "## Logo\nSupplied — in FrameMind HQ (project → Client portal).\n" : ""}`;
}

export function repoFiles(input: DocInput): { path: string; content: string; owned: boolean }[] {
  const claude = claudeOnGitHub();
  return [
    { path: "docs/FOUNDER_SUMMARY.md", content: founderSummary(input), owned: true },
    { path: "docs/CLIENT_REQUIREMENTS.md", content: clientRequirements(input), owned: true },
    { path: "docs/PRD.md", content: prd(input), owned: false },
    { path: "docs/Architecture.md", content: architecture(input), owned: false },
    { path: "docs/Rules.md", content: rules(input), owned: false },
    { path: "docs/Design.md", content: design(input), owned: false },
    { path: "docs/Tasks.md", content: tasksMd(input), owned: true },
    { path: "CLAUDE.md", content: claudeMd(input), owned: true },
    { path: ".github/workflows/ci.yml", content: CI_WORKFLOW, owned: true },
    // Claude's workflows go in only while Claude on GitHub is on (lib/dev/mode.ts)
    ...(claude
      ? [
          { path: ".github/workflows/claude-plan.yml", content: CLAUDE_PLAN_WORKFLOW, owned: true },
          { path: ".github/workflows/claude-build.yml", content: CLAUDE_BUILD_WORKFLOW, owned: true },
          { path: ".github/workflows/claude-review.yml", content: CLAUDE_REVIEW_WORKFLOW, owned: true },
        ]
      : []),
    { path: ".github/pull_request_template.md", content: PR_TEMPLATE, owned: false },
  ];
}
