export function tasksMd({ project, tasks, team }: DocInput) {
  const open = tasks.filter((t) => !["merged", "closed"].includes(s(t.devStatus)));
  const done = tasks.filter((t) => s(t.devStatus) === "merged");
  const row = (t: Rec) =>
    `### ${s(t.taskKey)} — ${s(t.title)}\n- **Type:** ${s(t.devType) || "feature"} · **Priority:** ${s(t.priority) || "medium"} · **Assignee:** ${nameOf(team, t.assigneeId)} · **Due:** ${s(t.dueDate) || "—"}\n- **Branch:** \`${s(t.branch)}\`\n- **Status:** ${s(t.devStatus) || "todo"}\n${s(t.description) ? `\n${s(t.description)}\n` : ""}${s(t.acceptance) ? `\n**Acceptance criteria**\n${lines(t.acceptance).map((l) => `- [ ] ${l.replace(/^[-*]\s*/, "")}`).join("\n")}\n` : ""}`;
  return `# Tasks — ${s(project.title)}

> Generated by FrameMind HQ — do not edit here; tasks are managed in HQ and this file is rewritten when they change.

## Open (${open.length})

${open.map(row).join("\n") || "_No open tasks._"}

## Done (${done.length})

${done.map((t) => `- ${s(t.taskKey)} — ${s(t.title)}`).join("\n") || "_None yet._"}
`;
}

export function claudeMd({ project, repoUrl }: DocInput) {
  return `# CLAUDE.md — ${s(project.title)}

> Generated by FrameMind HQ. Instructions for Claude Code in this repository.

## Before you start
1. Read \`docs/FOUNDER_SUMMARY.md\` first — it is the founder's decision on what we are building and overrides everything else.
   Then \`docs/PROJECT_PLAN.md\` (if present), \`docs/PRD.md\`, \`docs/Architecture.md\`, \`docs/Rules.md\` and \`docs/Design.md\`.
2. Find your task in \`docs/Tasks.md\` by its ID (e.g. FM-104). Work only on that task, on its branch.

## How to work
- Make sure you are on the task's branch (\`git branch --show-current\`); never commit to \`main\`.
- Start every commit message with the task ID: \`FM-104: …\`.
- Run the project's checks before pushing (lint, tests, build — see package.json).
- Push the branch; open the pull request from FrameMind HQ when the acceptance criteria are met.

## Don'ts
- Don't add secrets, keys or \`.env\` files.
- Don't change \`docs/Tasks.md\` or this file — HQ rewrites them.
- Don't add dependencies or restructure folders without the Tech Lead's OK.

Repository: ${repoUrl}
`;
}

export const CI_WORKFLOW = `name: CI
on:
  pull_request:
  push:
    branches: [main]
  # HQ starts it after Claude pushes from inside Actions (those pushes don't start workflows by themselves)
  workflow_dispatch:
permissions:
  contents: read
jobs:
  checks:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        if: hashFiles('package.json') != ''
        with:
          node-version: 22
      - name: Install
        if: hashFiles('package.json') != ''
        run: npm ci || npm install
      - name: Lint
        if: hashFiles('package.json') != ''
        run: npm run lint --if-present
      - name: Test
        if: hashFiles('package.json') != ''
        run: npm test --if-present
      - name: Build
        if: hashFiles('package.json') != ''
        run: npm run build --if-present
`;

