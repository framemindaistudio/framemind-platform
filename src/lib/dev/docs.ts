/**
 * The files HQ writes into every client repository. PRD, Architecture, Rules and Design are written once as a
 * starting draft and then belong to their owners (HQ never overwrites them); Tasks.md and CLAUDE.md are HQ's own and
 * are rewritten whenever tasks change, so Claude Code always works from the current list.
 *
 * Nothing here invents facts about the client: what HQ doesn't know is left as a clearly marked "to fill" line.
 */

import { CLAUDE_BUILD_WORKFLOW, CLAUDE_PLAN_WORKFLOW, CLAUDE_REVIEW_WORKFLOW } from "./workflows";
import { claudeOnGitHub } from "./mode";

type Rec = Record<string, unknown>;
const s = (v: unknown) => (v === undefined || v === null ? "" : String(v)).trim();
const TODO = (who: string) => `_To be written by the ${who}._`;

export interface DocInput {
  project: Rec;
  client?: Rec;
  submission?: Rec | null;
  tasks: Rec[];
  team: Rec[];
  repoUrl: string;
}

const lines = (v: unknown) =>
  s(v)
    .split(/\n+/)
    .map((x) => x.trim())
    .filter(Boolean);
const nameOf = (team: Rec[], id: unknown) => s(team.find((m) => m.id === s(id))?.name) || "Unassigned";

export function prd({ project, client, submission }: DocInput) {
  const sub = submission ?? {};
  return `# PRD — ${s(project.title)}

> Owner: Founder · Draft generated by FrameMind HQ from the client's approved requirements. Edit freely — HQ won't overwrite this file.

## Client
- **Organisation:** ${s(sub.company) || s(client?.name) || TODO("founder")}
- **Contact:** ${[s(sub.contactName) || s(client?.contactName), s(sub.email) || s(client?.email)].filter(Boolean).join(" · ") || TODO("founder")}
- **Current website:** ${s(sub.website) || "None given"}

## About the client
${s(sub.about) || TODO("founder")}

## Audience
${s(sub.audience) || TODO("founder")}

## Requirements
${s(sub.requirements) || s(project.brief) || TODO("founder")}

## Pages / sections
${lines(sub.pages).map((p) => `- ${p}`).join("\n") || TODO("founder")}

## Goals & success measures
${TODO("founder")}

## Out of scope
${TODO("founder")}

## Acceptance criteria (project level)
${TODO("founder")}

## Delivery
- Target date: ${s(project.dueDate) || "Not set yet"}
- Revision rounds included: ${s(project.revisionsAllowed) || "2"}
`;
}

